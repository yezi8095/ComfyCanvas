async fn generate_openai_image_edit(
    endpoint: String,
    api_key: String,
    prompt: String,
    model: String,
    image_data: String,
    size: Option<String>,
    quality: Option<String>,
) -> Result<String, String> {
    validate_provider_request("OpenAI 兼容接口", &endpoint, &api_key, &prompt, &model)?;
    let options = openai_image_options(&model, size, quality, true)?;
    validate_image_reference(&image_data, "参考图")?;
    if !image_data.starts_with("data:") {
        return Err("当前 OpenAI 图生图适配只接受本地图片 Data URL；请先导入图片再生成".into());
    }
    let (header, encoded) = image_data
        .split_once(',')
        .ok_or_else(|| "参考图不是有效的 Data URL".to_string())?;
    let mime = header
        .strip_prefix("data:")
        .and_then(|value| value.split(';').next())
        .unwrap_or("image/png");
    let extension = match mime {
        "image/jpeg" => "jpg",
        "image/webp" => "webp",
        _ => "png",
    };
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(encoded)
        .map_err(|error| error.to_string())?;
    let image_part = reqwest::multipart::Part::bytes(bytes)
        .file_name(format!("reference.{extension}"))
        .mime_str(mime)
        .map_err(|error| error.to_string())?;
    let mut form = reqwest::multipart::Form::new()
        .text("model", model)
        .text("prompt", prompt)
        .text("size", options.size)
        .part("image", image_part);
    if let Some(quality) = options.quality {
        form = form.text("quality", quality);
    }
    let base = endpoint.trim_end_matches('/');
    let url = if base.ends_with("/v1") {
        format!("{base}/images/edits")
    } else {
        format!("{base}/v1/images/edits")
    };
    let response = reqwest::Client::new()
        .post(url)
        .bearer_auth(api_key)
        .multipart(form)
        .send()
        .await
        .map_err(|error| provider_network_error("OpenAI 兼容接口", "图生图", &error))?;
    let response = provider_json_response("OpenAI 兼容接口", "图生图", response).await?;
    if let Some(encoded) = response
        .pointer("/data/0/b64_json")
        .and_then(serde_json::Value::as_str)
    {
        return Ok(format!("data:image/png;base64,{encoded}"));
    }
    if let Some(url) = response
        .pointer("/data/0/url")
        .and_then(serde_json::Value::as_str)
    {
        let url = reqwest::Url::parse(url)
            .map_err(|error| format!("图生图接口返回的图片地址无效：{error}"))?;
        let response = reqwest::get(url)
            .await
            .map_err(|error| provider_network_error("OpenAI 兼容接口", "下载图生图结果", &error))?;
        let bytes = provider_bytes_response("OpenAI 兼容接口", "下载图生图结果", response).await?;
        return Ok(format!(
            "data:image/png;base64,{}",
            base64::engine::general_purpose::STANDARD.encode(bytes)
        ));
    }
    Err("图生图接口没有返回图片数据".into())
}

#[tauri::command]
async fn generate_google_image(
    endpoint: String,
    api_key: String,
    prompt: String,
    model: String,
    ratio: String,
    resolution: String,
    image_data: Vec<String>,
) -> Result<String, String> {
    validate_provider_request("Google Gemini", &endpoint, &api_key, &prompt, &model)?;
    let endpoint = validated_http_endpoint("Google Gemini", &endpoint)?.trim_end_matches('/');
    let base = if endpoint.ends_with("/v1") || endpoint.ends_with("/v1beta") {
        endpoint.to_string()
    } else {
        format!("{endpoint}/v1beta")
    };
    let model = model.trim().trim_start_matches("models/");
    if model.is_empty() {
        return Err("请先填写 Gemini 图片模型".into());
    }
    if ![
        "1:1", "2:3", "3:2", "3:4", "4:3", "4:5", "5:4", "9:16", "16:9", "21:9",
    ]
    .contains(&ratio.trim())
    {
        return Err(format!("Gemini 图片适配不支持画面比例“{}”", ratio.trim()));
    }
    if image_data.len() > 14 {
        return Err(format!(
            "Gemini 图片生成最多接受 14 张参考图（当前 {} 张）",
            image_data.len()
        ));
    }
    let image_size = match resolution.trim().to_ascii_uppercase().as_str() {
        "1024" | "1K" => "1K",
        "2048" | "2K" => "2K",
        "4096" | "4K" => "4K",
        other => {
            return Err(format!(
                "Gemini 图片适配不支持分辨率“{other}”；请使用 1024、2048 或 4096"
            ))
        }
    };
    let supports_high_resolution = model.contains("gemini-3") && !model.contains("flash-lite");
    if image_size != "1K" && !supports_high_resolution {
        return Err(format!(
            "模型“{model}”当前仅接入 1K 图片合同；2K/4K 仅对已适配的 Gemini 3 非 Flash Lite 模型开放"
        ));
    }
    let mut parts = vec![serde_json::json!({"text": prompt})];
    for (index, data_url) in image_data.into_iter().enumerate() {
        let data_url =
            validate_image_reference(&data_url, &format!("第 {} 张 Gemini 参考图", index + 1))?;
        if !data_url.starts_with("data:") {
            return Err(format!(
                "第 {} 张 Gemini 参考图必须是 Data URL；当前 Gemini 内联请求不能直接传远程 URL",
                index + 1
            ));
        }
        let (header, encoded) = data_url
            .split_once(',')
            .ok_or_else(|| "Nano Banana 参考图不是有效的 Data URL".to_string())?;
        let mime_type = header
            .strip_prefix("data:")
            .and_then(|value| value.split(';').next())
            .unwrap_or("image/png");
        parts.push(serde_json::json!({
            "inlineData": { "mimeType": mime_type, "data": encoded }
        }));
    }
    let mut image_format = serde_json::json!({ "aspectRatio": ratio });
    if supports_high_resolution {
        image_format["imageSize"] = serde_json::Value::String(image_size.to_string());
    }
    let generation_config = serde_json::json!({
        "responseModalities": ["IMAGE"],
        "responseFormat": { "image": image_format }
    });
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(180))
        .build()
        .map_err(|error| format!("创建 Nano Banana 网络请求失败：{error}"))?;
    let response = client
        .post(format!("{base}/models/{model}:generateContent"))
        .header("x-goog-api-key", api_key.trim())
        .json(&serde_json::json!({
            "contents": [{ "parts": parts }],
            "generationConfig": generation_config
        }))
        .send()
        .await
        .map_err(|error| provider_network_error("Google Gemini", "生成图片", &error))?;
    let body = provider_json_response("Google Gemini", "生成图片", response).await?;
    let response_parts = body
        .pointer("/candidates/0/content/parts")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| format!("Nano Banana 没有返回候选图片：{body}"))?;
    for part in response_parts.iter().rev() {
        let encoded = part
            .pointer("/inlineData/data")
            .or_else(|| part.pointer("/inline_data/data"))
            .and_then(serde_json::Value::as_str);
        if let Some(encoded) = encoded {
            let mime_type = part
                .pointer("/inlineData/mimeType")
                .or_else(|| part.pointer("/inline_data/mime_type"))
                .and_then(serde_json::Value::as_str)
                .unwrap_or("image/png");
            return Ok(format!("data:{mime_type};base64,{encoded}"));
        }
    }
    Err("Nano Banana 返回了文本，但没有返回图片数据".into())
}

// 阿里云百炼（DashScope）万相视频采用异步任务协议：先创建任务，再查询任务状态。
// 放在 Rust 侧调用可以绕过 WebView 的跨域限制，同时 API Key 不会暴露到前端日志中。
fn wan_supported_mode(model: &str) -> &'static str {
    let model = model.trim().to_ascii_lowercase();
    if model.contains("kf2v") || model.contains("first-last") || model.contains("first_last") {
        "firstLast"
    } else if model.contains("i2v")
        || model.contains("image-to-video")
        || model.contains("image_to_video")
    {
        "image"
    } else {
        "text"
    }
}

fn validate_wan_video_contract<'a>(
    model: &str,
    mode: &str,
    ratio: &'a str,
    quality: &str,
    duration: u32,
    audio: bool,
) -> Result<(&'static str, &'a str), String> {
    let expected_mode = wan_supported_mode(model);
    if mode != expected_mode {
        return Err(format!(
            "万相模型“{}”当前只接入{}；请选择匹配模式，不能把参数静默改成另一种模式",
            model.trim(),
            match expected_mode {
                "text" => "文生视频",
                "image" => "图生视频",
                _ => "首尾帧视频",
            }
        ));
    }
    let quality = validate_video_quality(quality)?;
    let ratio = validate_video_ratio(ratio)?;
    if !matches!(ratio, "16:9" | "9:16") && quality != "720P" {
        return Err(format!(
            "万相当前适配在 {ratio} 比例使用平台固定画幅，只提供 720P 档位；480P/1080P 不会被静默忽略"
        ));
    }
    if !(5..=10).contains(&duration) {
        return Err("万相视频时长必须在 5 到 10 秒之间；当前请求不会自动改写时长".into());
    }
    if mode == "firstLast" {
        if duration != 5 {
            return Err("万相 kf2v 首尾帧视频固定为 5 秒；请将时长设为 5 秒".into());
        }
        if audio {
            return Err("万相 kf2v 首尾帧合同当前没有音频开关；请关闭音频后重试".into());
        }
    }
    Ok((quality, ratio))
}

