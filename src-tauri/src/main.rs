fn parse_mcp_body(body: &str) -> Result<serde_json::Value, String> {
    if let Ok(value) = serde_json::from_str::<serde_json::Value>(body) {
        return Ok(value);
    }
    let mut last = None;
    for line in body.lines() {
        if let Some(data) = line.strip_prefix("data:") {
            if let Ok(value) = serde_json::from_str::<serde_json::Value>(data.trim()) {
                last = Some(value);
            }
        }
    }
    last.ok_or_else(|| "MCP 服务没有返回有效 JSON 或 SSE data".into())
}

#[tauri::command]
async fn test_mcp_server(
    endpoint: String,
    token: Option<String>,
) -> Result<McpConnectionResult, String> {
    let endpoint = endpoint.trim();
    if endpoint.is_empty() {
        return Err("请填写 MCP Streamable HTTP 地址".into());
    }
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(30))
        .build()
        .map_err(|error| format!("创建 MCP 请求失败：{error}"))?;
    let mut modern_request = client
        .post(endpoint)
        .header("Accept", "application/json, text/event-stream")
        .header("MCP-Protocol-Version", "2026-07-28")
        .header("Mcp-Method", "tools/list")
        .json(&serde_json::json!({
            "jsonrpc": "2.0", "id": 1, "method": "tools/list",
            "params": {"_meta": {
                "io.modelcontextprotocol/protocolVersion": "2026-07-28",
                "io.modelcontextprotocol/clientInfo": {"name":"ComfyCanvas","version":"0.1.0"},
                "io.modelcontextprotocol/clientCapabilities": {}
            }}
        }));
    if let Some(value) = token.as_deref().filter(|value| !value.trim().is_empty()) {
        modern_request = modern_request.bearer_auth(value.trim());
    }
    if let Ok(response) = modern_request.send().await {
        if response.status().is_success() {
            if let Ok(body) = response.text().await {
                if let Ok(value) = parse_mcp_body(&body) {
                    if let Some(list) = value
                        .pointer("/result/tools")
                        .and_then(serde_json::Value::as_array)
                    {
                        let tools = list
                            .iter()
                            .filter_map(|tool| {
                                tool.get("name")
                                    .and_then(serde_json::Value::as_str)
                                    .map(|name| McpToolInfo {
                                        name: name.to_string(),
                                        description: tool
                                            .get("description")
                                            .and_then(serde_json::Value::as_str)
                                            .map(str::to_owned),
                                    })
                            })
                            .collect();
                        return Ok(McpConnectionResult {
                            server_name: "MCP 服务".into(),
                            protocol_version: "2026-07-28".into(),
                            tools,
                        });
                    }
                }
            }
        }
    }
    let send = |payload: serde_json::Value, session: Option<&str>| {
        let mut request = client
            .post(endpoint)
            .header("Accept", "application/json, text/event-stream")
            .header("MCP-Protocol-Version", "2025-11-25")
            .json(&payload);
        if let Some(value) = token.as_deref().filter(|value| !value.trim().is_empty()) {
            request = request.bearer_auth(value.trim());
        }
        if let Some(value) = session {
            request = request.header("Mcp-Session-Id", value);
        }
        request
    };
    let initialize_response = send(
        serde_json::json!({
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": "2025-11-25",
                "capabilities": {},
                "clientInfo": { "name": "ComfyCanvas", "version": "0.1.0" }
            }
        }),
        None,
    )
    .send()
    .await
    .map_err(|error| format!("无法连接 MCP 服务：{error}"))?;
    let status = initialize_response.status();
    let session = initialize_response
        .headers()
        .get("mcp-session-id")
        .and_then(|value| value.to_str().ok())
        .map(str::to_owned);
    let initialize_body = initialize_response
        .text()
        .await
        .map_err(|error| format!("无法读取 MCP 初始化响应：{error}"))?;
    if !status.is_success() {
        return Err(format!(
            "MCP 初始化失败（HTTP {status}）：{initialize_body}"
        ));
    }
    let initialize = parse_mcp_body(&initialize_body)?;
    if let Some(error) = initialize.get("error") {
        return Err(format!("MCP 初始化失败：{error}"));
    }
    let protocol_version = initialize
        .pointer("/result/protocolVersion")
        .and_then(serde_json::Value::as_str)
        .unwrap_or("2025-11-25")
        .to_string();
    let server_name = initialize
        .pointer("/result/serverInfo/name")
        .and_then(serde_json::Value::as_str)
        .unwrap_or("MCP 服务")
        .to_string();
    let _ = send(
        serde_json::json!({"jsonrpc":"2.0","method":"notifications/initialized"}),
        session.as_deref(),
    )
    .send()
    .await;
    let tools_response = send(
        serde_json::json!({"jsonrpc":"2.0","id":2,"method":"tools/list","params":{}}),
        session.as_deref(),
    )
    .send()
    .await
    .map_err(|error| format!("MCP tools/list 请求失败：{error}"))?;
    let tools_status = tools_response.status();
    let tools_body = tools_response
        .text()
        .await
        .map_err(|error| format!("无法读取 MCP 工具列表：{error}"))?;
    if !tools_status.is_success() {
        return Err(format!(
            "MCP tools/list 失败（HTTP {tools_status}）：{tools_body}"
        ));
    }
    let tools_value = parse_mcp_body(&tools_body)?;
    if let Some(error) = tools_value.get("error") {
        return Err(format!("MCP tools/list 失败：{error}"));
    }
    let tools = tools_value
        .pointer("/result/tools")
        .and_then(serde_json::Value::as_array)
        .ok_or("MCP 响应中没有 result.tools")?
        .iter()
        .filter_map(|tool| {
            tool.get("name")
                .and_then(serde_json::Value::as_str)
                .map(|name| McpToolInfo {
                    name: name.to_string(),
                    description: tool
                        .get("description")
                        .and_then(serde_json::Value::as_str)
                        .map(str::to_owned),
                })
        })
        .collect();
    Ok(McpConnectionResult {
        server_name,
        protocol_version,
        tools,
    })
}

#[tauri::command]
async fn discover_api_models(
    provider: String,
    endpoint: String,
    api_key: String,
) -> Result<Vec<String>, String> {
    let endpoint = validated_http_endpoint(&provider, &endpoint)?.trim_end_matches('/');
    if provider != "Ollama（本地）" {
        required_text(&api_key, "API Key 或 Access Key")?;
    }
    let url = if provider == "Ollama（本地）" {
        let base = endpoint.trim_end_matches("/v1");
        format!("{base}/api/tags")
    } else if provider == "阿里百炼·万相" {
        let root = endpoint
            .strip_suffix("/api/v1")
            .or_else(|| endpoint.strip_suffix("/compatible-mode/v1"))
            .unwrap_or(endpoint);
        format!("{root}/compatible-mode/v1/models")
    } else if endpoint.ends_with("/models") {
        endpoint.to_string()
    } else if endpoint.ends_with("/v1") {
        format!("{endpoint}/models")
    } else {
        format!("{endpoint}/v1/models")
    };
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(25))
        .build()
        .map_err(|error| format!("创建{provider}模型请求失败：{error}"))?;
    let mut request = client.get(&url);
    if !api_key.trim().is_empty() && provider != "Ollama（本地）" {
        request = request.bearer_auth(api_key.trim());
    }
    let response = request
        .send()
        .await
        .map_err(|error| provider_network_error(&provider, "读取模型列表", &error))?;
    let value = provider_json_response(&provider, "读取模型列表", response).await?;
    let list = value
        .get("data")
        .and_then(|v| v.as_array())
        .or_else(|| value.get("models").and_then(|v| v.as_array()))
        .ok_or("响应中没有 data/models 模型列表")?;
    let mut models: Vec<String> = list
        .iter()
        .filter_map(|item| {
            item.get("id")
                .and_then(|v| v.as_str())
                .or_else(|| item.get("name").and_then(|v| v.as_str()))
        })
        .map(str::to_string)
        .collect();
    models.sort();
    models.dedup();
    if models.is_empty() {
        return Err("接口返回了空模型列表".into());
    }
    Ok(models)
}

fn comfy_reachable(port: u16) -> bool {
    let address: SocketAddr = format!("127.0.0.1:{port}").parse().unwrap();
    let Ok(mut stream) = TcpStream::connect_timeout(&address, Duration::from_millis(650)) else {
        return false;
    };
    let _ = stream.set_read_timeout(Some(Duration::from_millis(900)));
    let _ = stream.set_write_timeout(Some(Duration::from_millis(900)));
    if stream
        .write_all(b"GET /system_stats HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n")
        .is_err()
    {
        return false;
    }
    let mut response = [0u8; 512];
    let Ok(length) = stream.read(&mut response) else {
        return false;
    };
    let text = String::from_utf8_lossy(&response[..length]);
    text.starts_with("HTTP/1.1 200")
}

fn comfyui_candidates() -> Vec<PathBuf> {
    let mut candidates = Vec::new();
    if let Ok(configured) = env::var("YM_COMFYUI_PATH") {
        candidates.push(PathBuf::from(configured));
    }
    if let Ok(profile) = env::var("USERPROFILE") {
        let profile = PathBuf::from(profile);
        candidates.push(profile.join("ComfyUI"));
        candidates.push(profile.join("Documents").join("ComfyUI"));
        candidates.push(profile.join("Desktop").join("ComfyUI"));
    }
    for drive in ["C:", "D:", "E:", "F:"] {
        let root = PathBuf::from(format!(r"{drive}\"));
        candidates.push(root.join("ComfyUI"));
        candidates.push(root.join("ComfyUI").join("ComfyUI"));
        candidates.push(root.join("ComfyUI_windows_portable").join("ComfyUI"));
        candidates.push(root.join("ComfyUI-aki-v2").join("ComfyUI"));
    }
    candidates
}

fn usable_ffmpeg(path: &Path) -> bool {
    Command::new(path)
        .arg("-version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

fn find_ffmpeg() -> Result<PathBuf, String> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(configured) = env::var("YM_FFMPEG_PATH") {
        candidates.push(PathBuf::from(configured));
    }
    if let Ok(executable) = env::current_exe() {
        if let Some(folder) = executable.parent() {
            candidates.push(folder.join("ffmpeg.exe"));
            candidates.push(folder.join("resources").join("ffmpeg.exe"));
        }
    }
    candidates.push(PathBuf::from("ffmpeg"));
    candidates
        .into_iter()
        .find(|path| usable_ffmpeg(path))
        .ok_or_else(|| {
            "未找到 FFmpeg。请将 ffmpeg.exe 放到亿幕画布程序旁，或设置环境变量 YM_FFMPEG_PATH。"
                .into()
        })
}

