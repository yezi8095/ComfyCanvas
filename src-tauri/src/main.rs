struct OpenAiImageOptions {
    size: String,
    quality: Option<String>,
}

fn openai_image_options(
    model: &str,
    requested_size: Option<String>,
    requested_quality: Option<String>,
    editing: bool,
) -> Result<OpenAiImageOptions, String> {
    let normalized_model = model.trim().to_ascii_lowercase();
    let is_gpt_image = normalized_model.contains("gpt-image");
    let is_dall_e_3 =
        normalized_model.contains("dall-e-3") || normalized_model.contains("dall·e-3");
    let is_dall_e_2 =
        normalized_model.contains("dall-e-2") || normalized_model.contains("dall·e-2");

    if editing && is_dall_e_3 {
        return Err("DALL·E 3 不支持图片编辑；请改用 GPT Image 或 DALL·E 2".into());
    }

    let (allowed_sizes, default_size): (&[&str], &str) = if is_gpt_image {
        (
            &["1024x1024", "1536x1024", "1024x1536", "auto"],
            "1024x1024",
        )
    } else if is_dall_e_3 {
        (&["1024x1024", "1792x1024", "1024x1792"], "1024x1024")
    } else if is_dall_e_2 {
        (&["256x256", "512x512", "1024x1024"], "1024x1024")
    } else {
        // OpenAI-compatible services do not share a universal arbitrary-size
        // contract. Keep the historical square request unless that adapter is
        // given its own explicit capability mapping.
        (&["1024x1024"], "1024x1024")
    };
    let size = requested_size
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .unwrap_or(default_size);
    if !allowed_sizes.contains(&size) {
        return Err(format!(
            "模型“{}”不支持图片尺寸 {size}；可用尺寸：{}",
            model.trim(),
            allowed_sizes.join("、")
        ));
    }

    let (allowed_qualities, default_quality): (&[&str], Option<&str>) = if is_gpt_image {
        (&["auto", "low", "medium", "high"], Some("low"))
    } else if is_dall_e_3 {
        (&["standard", "hd"], Some("standard"))
    } else if is_dall_e_2 {
        (&[], None)
    } else {
        // Preserve the old OpenAI-compatible request when the caller has not
        // yet supplied a provider-specific capability profile.
        (
            &["auto", "low", "medium", "high", "standard", "hd"],
            Some("low"),
        )
    };
    let quality = requested_quality
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(str::to_ascii_lowercase)
        .or_else(|| default_quality.map(str::to_owned));
    if let Some(value) = quality.as_deref() {
        if !allowed_qualities.contains(&value) {
            return Err(if allowed_qualities.is_empty() {
                format!("模型“{}”不接受 quality 参数", model.trim())
            } else {
                format!(
                    "模型“{}”不支持图片质量 {value}；可用质量：{}",
                    model.trim(),
                    allowed_qualities.join("、")
                )
            });
        }
    }

    Ok(OpenAiImageOptions {
        size: size.to_string(),
        quality,
    })
}

#[tauri::command]
async fn generate_openai_image(
    endpoint: String,
    api_key: String,
    prompt: String,
    model: String,
    size: Option<String>,
    quality: Option<String>,
) -> Result<String, String> {
    validate_provider_request("OpenAI 兼容接口", &endpoint, &api_key, &prompt, &model)?;
    let options = openai_image_options(&model, size, quality, false)?;
    let base = endpoint.trim_end_matches('/');
    let url = if base.ends_with("/v1") {
        format!("{base}/images/generations")
    } else {
        format!("{base}/v1/images/generations")
    };
    let mut body = serde_json::json!({
        "model": model,
        "prompt": prompt,
        "n": 1,
        "size": options.size,
    });
    if let Some(quality) = options.quality {
        body["quality"] = serde_json::Value::String(quality);
    }
    let response = reqwest::Client::new()
        .post(url)
        .bearer_auth(api_key)
        .json(&body)
        .send()
        .await
        .map_err(|error| provider_network_error("OpenAI 兼容接口", "生成图片", &error))?;
    let response = provider_json_response("OpenAI 兼容接口", "生成图片", response).await?;
    if let Some(encoded) = response
        .pointer("/data/0/b64_json")
        .and_then(serde_json::Value::as_str)
    {
        return Ok(format!("data:image/png;base64,{encoded}"));
    }
    if let Some(url) = response
        .pointer("/data/0/url")
        .and_then(serde_json::Value::as_str)
    {
        let url = reqwest::Url::parse(url)
            .map_err(|error| format!("OpenAI 返回的图片地址无效：{error}"))?;
        let response = reqwest::get(url)
            .await
            .map_err(|error| provider_network_error("OpenAI 兼容接口", "下载生成图片", &error))?;
        let bytes = provider_bytes_response("OpenAI 兼容接口", "下载生成图片", response).await?;
        return Ok(format!(
            "data:image/png;base64,{}",
            base64::engine::general_purpose::STANDARD.encode(bytes)
        ));
    }
    Err("OpenAI 没有返回图片数据".into())
}

