fn comfy_output_view_url(
    endpoint: &str,
    filename: &str,
    subfolder: Option<&str>,
) -> Result<reqwest::Url, String> {
    let endpoint = validated_http_endpoint("ComfyUI", endpoint)?;
    let filename = filename.trim();
    if filename.is_empty()
        || filename.chars().count() > 260
        || filename.contains(['/', '\\'])
        || filename.chars().any(char::is_control)
    {
        return Err("ComfyUI 输出文件名无效".into());
    }
    let subfolder = subfolder.unwrap_or("").trim();
    if subfolder.chars().count() > 520
        || subfolder.contains(['\\', ':'])
        || subfolder.chars().any(char::is_control)
        || subfolder
            .split('/')
            .any(|part| matches!(part, "." | ".."))
    {
        return Err("ComfyUI 输出子目录无效".into());
    }
    let mut url = reqwest::Url::parse(&format!("{}/view", endpoint.trim_end_matches('/')))
        .map_err(|error| format!("ComfyUI 输出地址无效：{error}"))?;
    url.query_pairs_mut()
        .append_pair("filename", filename)
        .append_pair("subfolder", subfolder)
        .append_pair("type", "output");
    Ok(url)
}

fn validate_workspace_identifier(value: &str, label: &str) -> Result<String, String> {
    let value = value.trim();
    if value.is_empty() {
        return Err(format!("{label}不能为空"));
    }
    if value.len() > 128 {
        return Err(format!("{label}不能超过 128 个字符"));
    }
    let mut chars = value.chars();
    if !chars
        .next()
        .is_some_and(|character| character.is_ascii_alphanumeric())
        || !value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
    {
        return Err(format!(
            "{label}只能使用英文字母、数字、连字符或下划线，且必须以字母或数字开头"
        ));
    }
    Ok(value.to_string())
}

fn sanitize_workspace_filename(value: &str) -> Result<String, String> {
    let value = value.trim();
    if value.is_empty() {
        return Err("素材文件名不能为空".into());
    }
    if value.chars().count() > 160 {
        return Err("素材文件名不能超过 160 个字符".into());
    }
    // Check the raw value before sanitizing. Silently flattening `../foo` or a
    // Windows drive path would make a malicious request look successful.
    if value == "."
        || value == ".."
        || value.contains(['/', '\\', ':'])
        || Path::new(value).is_absolute()
        || value.chars().any(char::is_control)
    {
        return Err("素材文件名不能包含路径、盘符或控制字符".into());
    }

    let mut result: String = value
        .chars()
        .map(|character| {
            if character.is_alphanumeric() || matches!(character, '.' | '_' | '-' | ' ') {
                character
            } else {
                '_'
            }
        })
        .collect();
    // Windows does not accept names ending with a period or whitespace.
    result = result
        .trim_matches(|character| character == ' ' || character == '.')
        .to_string();
    if result.is_empty() {
        return Err("素材文件名不包含可用字符".into());
    }

    let leading_name = result
        .split('.')
        .next()
        .unwrap_or_default()
        .to_ascii_uppercase();
    let is_reserved_device = matches!(
        leading_name.as_str(),
        "CON"
            | "PRN"
            | "AUX"
            | "NUL"
            | "COM1"
            | "COM2"
            | "COM3"
            | "COM4"
            | "COM5"
            | "COM6"
            | "COM7"
            | "COM8"
            | "COM9"
            | "LPT1"
            | "LPT2"
            | "LPT3"
            | "LPT4"
            | "LPT5"
            | "LPT6"
            | "LPT7"
            | "LPT8"
            | "LPT9"
    );
    if is_reserved_device {
        result = format!("file_{result}");
    }
    Ok(result)
}

fn workspace_asset_root<R: tauri::Runtime>(app: &tauri::AppHandle<R>) -> Result<PathBuf, String> {
    app.path()
        .app_local_data_dir()
        .map(|path| path.join("workspace-v1"))
        .map_err(|error| format!("无法定位应用素材目录：{error}"))
}

fn has_workspace_assets_directory_shape(root: &Path, directory: &Path) -> bool {
    let Ok(relative) = directory.strip_prefix(root) else {
        return false;
    };
    let parts = relative.components().collect::<Vec<_>>();
    parts.len() == 3
        && parts[0].as_os_str() == "projects"
        && validate_workspace_identifier(&parts[1].as_os_str().to_string_lossy(), "项目 ID")
            .is_ok()
        && parts[2].as_os_str() == "assets"
}

fn authorize_workspace_assets_directory<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    directory: &Path,
) -> Result<PathBuf, String> {
    let root = workspace_asset_root(app)?;
    fs::create_dir_all(&root).map_err(|error| format!("无法创建应用素材目录：{error}"))?;
    let canonical_root = fs::canonicalize(&root)
        .map_err(|error| format!("无法校验应用素材目录：{error}"))?;
    let canonical_directory = fs::canonicalize(directory)
        .map_err(|error| format!("无法校验项目素材目录：{error}"))?;
    if !has_workspace_assets_directory_shape(&canonical_root, &canonical_directory) {
        return Err("项目素材目录不在应用专属存储边界内".into());
    }
    app.asset_protocol_scope()
        .allow_directory(&canonical_directory, true)
        .map_err(|error| format!("无法授权项目素材预览：{error}"))?;
    Ok(canonical_directory)
}

fn initialize_workspace_asset_scope<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
) -> Result<(), String> {
    let root = workspace_asset_root(app)?;
    let projects = root.join("projects");
    fs::create_dir_all(&projects).map_err(|error| format!("无法创建项目素材目录：{error}"))?;
    let entries = fs::read_dir(&projects).map_err(|error| format!("无法扫描项目素材目录：{error}"))?;
    for entry in entries.flatten() {
        let project_id = entry.file_name().to_string_lossy().to_string();
        if validate_workspace_identifier(&project_id, "项目 ID").is_err() {
            continue;
        }
        let assets = entry.path().join("assets");
        if assets.is_dir() {
            authorize_workspace_assets_directory(app, &assets)?;
        }
    }
    Ok(())
}

fn authorized_media_source_path<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    path: &str,
) -> Result<PathBuf, String> {
    let source = Path::new(path);
    let canonical = fs::canonicalize(source)
        .map_err(|error| format!("素材文件不存在或无法读取（{}）：{error}", source.display()))?;
    if !canonical.is_file() {
        return Err(format!("素材文件不存在：{}", source.display()));
    }
    if !app.asset_protocol_scope().is_allowed(&canonical) {
        return Err(
            "素材不在应用受管目录，也不是本次通过文件选择器授权的文件；请重新导入素材后再试"
                .into(),
        );
    }
    Ok(canonical)
}

fn managed_workspace_child(parent: &Path, file_name: &str) -> Result<PathBuf, String> {
    if file_name.is_empty()
        || file_name == "."
        || file_name == ".."
        || file_name.contains(['/', '\\', ':'])
        || Path::new(file_name).is_absolute()
    {
        return Err("素材存储文件名校验失败".into());
    }
    let candidate = parent.join(file_name);
    if candidate.starts_with(parent) {
        Ok(candidate)
    } else {
        Err("素材存储路径校验失败".into())
    }
}

fn normalize_workspace_mime_type(value: Option<String>) -> Result<Option<String>, String> {
    let Some(value) = value else {
        return Ok(None);
    };
    let value = value.trim();
    if value.is_empty() {
        return Ok(None);
    }
    if value.len() > 180 || value.chars().any(char::is_control) {
        return Err("素材 MIME 类型无效".into());
    }
    Ok(Some(value.to_string()))
}

fn next_workspace_asset_upload_id() -> String {
    let sequence = WORKSPACE_ASSET_UPLOAD_SEQUENCE.fetch_add(1, Ordering::Relaxed);
    let millis = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis();
    format!("upload-{}-{millis}-{sequence}", std::process::id())
}

fn remove_workspace_file_best_effort(path: &Path) {
    let _ = fs::remove_file(path);
}

fn cleanup_stale_workspace_asset_parts(root: &Path) {
    let uploads_dir = root.join("uploads");
    let Ok(entries) = fs::read_dir(uploads_dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|value| value.to_str()) != Some("part") {
            continue;
        }
        let is_stale = entry
            .metadata()
            .and_then(|metadata| metadata.modified())
            .ok()
            .and_then(|modified| modified.elapsed().ok())
            .is_some_and(|age| age > WORKSPACE_ASSET_PART_TTL);
        if is_stale {
            remove_workspace_file_best_effort(&path);
        }
    }
}

fn cleanup_expired_workspace_asset_uploads(
    state: &WorkspaceAssetUploadState,
) -> Result<(), String> {
    let expired_paths = {
        let mut uploads = state
            .uploads
            .lock()
            .map_err(|_| "素材上传会话已损坏，请重试".to_string())?;
        let expired_ids: Vec<String> = uploads
            .iter()
            .filter_map(|(upload_id, upload)| {
                upload
                    .created_at
                    .elapsed()
                    .ok()
                    .filter(|age| *age > WORKSPACE_ASSET_UPLOAD_TTL)
                    .map(|_| upload_id.clone())
            })
            .collect();
        expired_ids
            .into_iter()
            .filter_map(|upload_id| uploads.remove(&upload_id).map(|upload| upload.temp_path))
            .collect::<Vec<_>>()
    };
    for path in expired_paths {
        remove_workspace_file_best_effort(&path);
    }
    Ok(())
}

fn decode_workspace_asset_chunk(value: &str) -> Result<Vec<u8>, String> {
    let value = value.trim();
    if value.is_empty() {
        return Err("上传分块不能为空".into());
    }
    // Base64 expands by about 4/3. Check before decode to keep one IPC call
    // from forcing an unexpectedly large allocation.
    if value.len() > WORKSPACE_ASSET_MAX_CHUNK_BYTES.saturating_mul(2) {
        return Err("单个上传分块不能超过 16 MB".into());
    }
    let decoded = base64::engine::general_purpose::STANDARD
        .decode(value)
        .or_else(|_| base64::engine::general_purpose::STANDARD_NO_PAD.decode(value))
        .map_err(|error| format!("上传分块不是有效 Base64：{error}"))?;
    if decoded.len() > WORKSPACE_ASSET_MAX_CHUNK_BYTES {
        return Err("单个上传分块不能超过 16 MB".into());
    }
    Ok(decoded)
}

#[tauri::command]
fn begin_workspace_asset(
    app: tauri::AppHandle,
    state: tauri::State<'_, WorkspaceAssetUploadState>,
    project_id: String,
    asset_id: String,
    filename: String,
    mime_type: Option<String>,
    total_bytes: Option<u64>,
) -> Result<WorkspaceAssetUploadStarted, String> {
    let project_id = validate_workspace_identifier(&project_id, "项目 ID")?;
    let asset_id = validate_workspace_identifier(&asset_id, "素材 ID")?;
    let file_name = sanitize_workspace_filename(&filename)?;
    let mime_type = normalize_workspace_mime_type(mime_type)?;
    if total_bytes.is_some_and(|bytes| bytes > WORKSPACE_ASSET_MAX_BYTES) {
        return Err("单个素材不能超过 1 GB".into());
    }

    cleanup_expired_workspace_asset_uploads(state.inner())?;
    let root = workspace_asset_root(&app)?;
    let assets_dir = root.join("projects").join(&project_id).join("assets");
    let uploads_dir = root.join("uploads");
    fs::create_dir_all(&assets_dir).map_err(|error| format!("无法创建项目素材目录：{error}"))?;
    fs::create_dir_all(&uploads_dir).map_err(|error| format!("无法创建素材临时目录：{error}"))?;
    // The global asset protocol starts empty. Only this concrete per-project
    // assets directory is exposed to the WebView; uploads and every other
    // file on the machine remain outside the protocol scope.
    authorize_workspace_assets_directory(&app, &assets_dir)?;
    cleanup_stale_workspace_asset_parts(&root);

    let stored_file_name = format!("{asset_id}--{file_name}");
    let final_path = managed_workspace_child(&assets_dir, &stored_file_name)?;
    if final_path.exists() {
        return Err("该项目已存在相同素材 ID；请创建新的素材再上传".into());
    }
    let upload_id = next_workspace_asset_upload_id();
    let temp_path = managed_workspace_child(&uploads_dir, &format!("{upload_id}.part"))?;
    OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp_path)
        .map_err(|error| format!("无法创建素材临时文件：{error}"))?;

    let upload = WorkspaceAssetUpload {
        project_id: project_id.clone(),
        asset_id: asset_id.clone(),
        file_name: file_name.clone(),
        mime_type: mime_type.clone(),
        expected_bytes: total_bytes,
        bytes_written: 0,
        temp_path: temp_path.clone(),
        final_path,
        created_at: SystemTime::now(),
    };
    if let Err(_) = state
        .uploads
        .lock()
        .map_err(|_| "素材上传会话已损坏，请重试".to_string())
        .map(|mut uploads| uploads.insert(upload_id.clone(), upload))
    {
        remove_workspace_file_best_effort(&temp_path);
        return Err("素材上传会话已损坏，请重试".into());
    }

    Ok(WorkspaceAssetUploadStarted {
        upload_id,
        project_id,
        asset_id,
        file_name,
        mime_type,
        expected_bytes: total_bytes,
        bytes_written: 0,
        max_bytes: WORKSPACE_ASSET_MAX_BYTES,
    })
}

#[tauri::command]
fn append_workspace_asset_chunk(
    state: tauri::State<'_, WorkspaceAssetUploadState>,
    upload_id: String,
    base64_chunk: String,
) -> Result<WorkspaceAssetChunkProgress, String> {
    let upload_id = validate_workspace_identifier(&upload_id, "上传会话 ID")?;
    let chunk = decode_workspace_asset_chunk(&base64_chunk)?;
    let mut uploads = state
        .uploads
        .lock()
        .map_err(|_| "素材上传会话已损坏，请重试".to_string())?;
    let (temp_path, next_bytes, expected_bytes) = {
        let upload = uploads
            .get(&upload_id)
            .ok_or("上传会话不存在、已过期或已经结束")?;
        let next_bytes = upload
            .bytes_written
            .checked_add(chunk.len() as u64)
            .ok_or("素材大小计算溢出")?;
        (upload.temp_path.clone(), next_bytes, upload.expected_bytes)
    };

    if next_bytes > WORKSPACE_ASSET_MAX_BYTES
        || expected_bytes.is_some_and(|expected| next_bytes > expected)
    {
        let temp_path = uploads.remove(&upload_id).map(|upload| upload.temp_path);
        drop(uploads);
        if let Some(temp_path) = temp_path {
            remove_workspace_file_best_effort(&temp_path);
        }
        return Err("素材上传大小超过声明大小或 1 GB 上限，已取消本次上传".into());
    }

    let write_result = (|| -> Result<(), String> {
        let mut file = OpenOptions::new()
            .append(true)
            .open(&temp_path)
            .map_err(|error| format!("无法打开素材临时文件：{error}"))?;
        file.write_all(&chunk)
            .map_err(|error| format!("写入素材分块失败：{error}"))
    })();
    if let Err(error) = write_result {
        let temp_path = uploads.remove(&upload_id).map(|upload| upload.temp_path);
        drop(uploads);
        if let Some(temp_path) = temp_path {
            remove_workspace_file_best_effort(&temp_path);
        }
        return Err(error);
    }
    let upload = uploads
        .get_mut(&upload_id)
        .ok_or("上传会话已在写入过程中结束")?;
    upload.bytes_written = next_bytes;
    Ok(WorkspaceAssetChunkProgress {
        upload_id,
        bytes_written: next_bytes,
        expected_bytes,
    })
}

/// Flush a completed upload before its atomic rename. Windows requires a
/// handle opened with write access for `FlushFileBuffers`; a read-only handle
/// returns `ERROR_ACCESS_DENIED` even though reading the file itself succeeds.
fn sync_workspace_asset_temp_file(path: &Path) -> Result<(), String> {
    OpenOptions::new()
        .write(true)
        .open(path)
        .and_then(|file| file.sync_all())
        .map_err(|error| format!("无法完成素材临时文件：{error}"))
}

#[tauri::command]
fn commit_workspace_asset(
    state: tauri::State<'_, WorkspaceAssetUploadState>,
    upload_id: String,
) -> Result<ManagedWorkspaceAssetRecord, String> {
    let upload_id = validate_workspace_identifier(&upload_id, "上传会话 ID")?;
    let upload = state
        .uploads
        .lock()
        .map_err(|_| "素材上传会话已损坏，请重试".to_string())?
        .remove(&upload_id)
        .ok_or("上传会话不存在、已过期或已经结束")?;

    let result = (|| -> Result<ManagedWorkspaceAssetRecord, String> {
        let actual_bytes = fs::metadata(&upload.temp_path)
            .map_err(|error| format!("无法读取素材临时文件：{error}"))?
            .len();
        if actual_bytes != upload.bytes_written {
            return Err("素材上传数据不完整；请重新上传".into());
        }
        if upload
            .expected_bytes
            .is_some_and(|expected| expected != actual_bytes)
        {
            return Err("素材实际大小与声明大小不一致；请重新上传".into());
        }
        if actual_bytes > WORKSPACE_ASSET_MAX_BYTES {
            return Err("单个素材不能超过 1 GB".into());
        }
        sync_workspace_asset_temp_file(&upload.temp_path)?;
        if upload.final_path.exists() {
            return Err("该项目已存在相同素材 ID；请创建新的素材再上传".into());
        }
        // Both paths live below the same app-local workspace root, so this is
        // an atomic rename rather than a copy into a frontend-provided path.
        fs::rename(&upload.temp_path, &upload.final_path)
            .map_err(|error| format!("无法提交素材文件：{error}"))?;
        Ok(ManagedWorkspaceAssetRecord {
            project_id: upload.project_id,
            asset_id: upload.asset_id,
            file_name: upload.file_name,
            mime_type: upload.mime_type,
            bytes: actual_bytes,
            local_path: upload.final_path.to_string_lossy().to_string(),
        })
    })();
    if result.is_err() {
        remove_workspace_file_best_effort(&upload.temp_path);
    }
    result
}

/// Download a generated ComfyUI file from the Rust process and commit it
/// directly into the managed workspace store. WebView requests include the
/// `http://tauri.localhost` Origin, which some ComfyUI installations reject
/// with 403; the backend request deliberately does not depend on browser CORS.
#[tauri::command]
async fn cache_comfy_output_media(
    app: tauri::AppHandle,
    endpoint: String,
    filename: String,
    subfolder: Option<String>,
    project_id: String,
    asset_id: String,
) -> Result<ManagedWorkspaceAssetRecord, String> {
    let project_id = validate_workspace_identifier(&project_id, "项目 ID")?;
    let asset_id = validate_workspace_identifier(&asset_id, "素材 ID")?;
    let view_url = comfy_output_view_url(&endpoint, &filename, subfolder.as_deref())?;
    let file_name = sanitize_workspace_filename(&filename)?;

    let root = workspace_asset_root(&app)?;
    let assets_dir = root.join("projects").join(&project_id).join("assets");
    let uploads_dir = root.join("uploads");
    fs::create_dir_all(&assets_dir).map_err(|error| format!("无法创建项目素材目录：{error}"))?;
    fs::create_dir_all(&uploads_dir).map_err(|error| format!("无法创建素材临时目录：{error}"))?;
    authorize_workspace_assets_directory(&app, &assets_dir)?;
    cleanup_stale_workspace_asset_parts(&root);

    let stored_file_name = format!("{asset_id}--{file_name}");
    let final_path = managed_workspace_child(&assets_dir, &stored_file_name)?;
    if final_path.exists() {
        return Err("该项目已存在相同素材 ID；请创建新的素材再缓存".into());
    }
    let download_id = next_workspace_asset_upload_id();
    let temp_path = managed_workspace_child(&uploads_dir, &format!("{download_id}.part"))?;

    let result = async {
        let mut response = reqwest::Client::new()
            .get(view_url)
            .send()
            .await
            .map_err(|error| format!("无法从 ComfyUI 下载生成结果：{error}"))?
            .error_for_status()
            .map_err(|error| format!("ComfyUI 生成结果下载失败：{error}"))?;
        let expected_bytes = response.content_length();
        if expected_bytes.is_some_and(|bytes| bytes > WORKSPACE_ASSET_MAX_BYTES) {
            return Err("ComfyUI 生成结果超过 1 GB，不能写入画布素材库".into());
        }
        let mime_type = normalize_workspace_mime_type(
            response
                .headers()
                .get(reqwest::header::CONTENT_TYPE)
                .and_then(|value| value.to_str().ok())
                .map(str::to_string),
        )?;
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temp_path)
            .map_err(|error| format!("无法创建 ComfyUI 结果临时文件：{error}"))?;
        let mut bytes_written = 0_u64;
        while let Some(chunk) = response
            .chunk()
            .await
            .map_err(|error| format!("读取 ComfyUI 结果数据失败：{error}"))?
        {
            bytes_written = bytes_written
                .checked_add(chunk.len() as u64)
                .ok_or("ComfyUI 结果大小计算溢出")?;
            if bytes_written > WORKSPACE_ASSET_MAX_BYTES {
                return Err("ComfyUI 生成结果超过 1 GB，已取消缓存".into());
            }
            file.write_all(&chunk)
                .map_err(|error| format!("写入 ComfyUI 结果失败：{error}"))?;
        }
        if bytes_written == 0 {
            return Err("ComfyUI 返回的生成结果为空".into());
        }
        if expected_bytes.is_some_and(|expected| expected != bytes_written) {
            return Err("ComfyUI 生成结果下载不完整，请重试".into());
        }
        file.sync_all()
            .map_err(|error| format!("无法完成 ComfyUI 结果缓存：{error}"))?;
        drop(file);
        fs::rename(&temp_path, &final_path)
            .map_err(|error| format!("无法提交 ComfyUI 结果缓存：{error}"))?;
        Ok(ManagedWorkspaceAssetRecord {
            project_id,
            asset_id,
            file_name,
            mime_type,
            bytes: bytes_written,
            local_path: final_path.to_string_lossy().to_string(),
        })
    }
    .await;
    if result.is_err() {
        remove_workspace_file_best_effort(&temp_path);
    }
    result
}

#[tauri::command]
fn abort_workspace_asset(
    state: tauri::State<'_, WorkspaceAssetUploadState>,
    upload_id: String,
) -> Result<WorkspaceAssetAbortResult, String> {
    let upload_id = validate_workspace_identifier(&upload_id, "上传会话 ID")?;
    let upload = state
        .uploads
        .lock()
        .map_err(|_| "素材上传会话已损坏，请重试".to_string())?
        .remove(&upload_id);
    if let Some(upload) = upload {
        remove_workspace_file_best_effort(&upload.temp_path);
        Ok(WorkspaceAssetAbortResult {
            upload_id,
            aborted: true,
        })
    } else {
        // Idempotent aborts make renderer cleanup safe even after an earlier
        // commit or a failed write already removed the session.
        Ok(WorkspaceAssetAbortResult {
            upload_id,
            aborted: false,
        })
    }
}

fn split_workspace_asset_file_name(value: &str) -> Option<(&str, &str)> {
    let (asset_id, file_name) = value.split_once("--")?;
    if validate_workspace_identifier(asset_id, "素材 ID").is_err() || file_name.is_empty() {
        return None;
    }
    Some((asset_id, file_name))
}

fn exact_workspace_asset_file_name(value: &str, asset_id: &str) -> bool {
    value
        .strip_prefix(asset_id)
        .and_then(|suffix| suffix.strip_prefix("--"))
        .is_some_and(|file_name| !file_name.is_empty())
}

fn existing_workspace_assets_directory<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    project_id: &str,
) -> Result<Option<PathBuf>, String> {
    let root = workspace_asset_root(app)?;
    let assets = root.join("projects").join(project_id).join("assets");
    if !assets.exists() {
        return Ok(None);
    }
    authorize_workspace_assets_directory(app, &assets).map(Some)
}

/// List metadata only from one exact app-managed project directory. The
/// renderer cannot supply a path, so this command cannot enumerate arbitrary
/// folders on the machine.
#[tauri::command]
fn list_workspace_assets(
    app: tauri::AppHandle,
    project_id: String,
) -> Result<Vec<ManagedWorkspaceAssetRecord>, String> {
    let project_id = validate_workspace_identifier(&project_id, "项目 ID")?;
    let Some(assets_dir) = existing_workspace_assets_directory(&app, &project_id)? else {
        return Ok(Vec::new());
    };
    let entries =
        fs::read_dir(&assets_dir).map_err(|error| format!("无法扫描项目素材目录：{error}"))?;
    let mut records = Vec::new();
    for entry in entries.flatten() {
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        // Never follow symlinks or recurse. Managed uploads are plain files.
        if !file_type.is_file() {
            continue;
        }
        let stored_name = entry.file_name().to_string_lossy().to_string();
        let Some((asset_id, file_name)) = split_workspace_asset_file_name(&stored_name) else {
            continue;
        };
        let bytes = entry.metadata().map(|metadata| metadata.len()).unwrap_or(0);
        records.push(ManagedWorkspaceAssetRecord {
            project_id: project_id.clone(),
            asset_id: asset_id.to_string(),
            file_name: file_name.to_string(),
            mime_type: None,
            bytes,
            local_path: entry.path().to_string_lossy().to_string(),
        });
    }
    records.sort_by(|left, right| {
        left.asset_id
            .cmp(&right.asset_id)
            .then_with(|| left.file_name.cmp(&right.file_name))
    });
    Ok(records)
}

/// Delete one exact asset id from one exact project. There is intentionally no
/// recursive/project-wide delete variant. If disk contents are ambiguous, the
/// command refuses to guess and leaves every file untouched.
#[tauri::command]
fn delete_workspace_asset(
    app: tauri::AppHandle,
    project_id: String,
    asset_id: String,
) -> Result<WorkspaceAssetDeleteResult, String> {
    let project_id = validate_workspace_identifier(&project_id, "项目 ID")?;
    let asset_id = validate_workspace_identifier(&asset_id, "素材 ID")?;
    let Some(assets_dir) = existing_workspace_assets_directory(&app, &project_id)? else {
        return Ok(WorkspaceAssetDeleteResult {
            project_id,
            asset_id,
            deleted: false,
        });
    };
    let matches = fs::read_dir(&assets_dir)
        .map_err(|error| format!("无法扫描项目素材目录：{error}"))?
        .flatten()
        .filter(|entry| entry.file_type().is_ok_and(|file_type| file_type.is_file()))
        .filter(|entry| {
            exact_workspace_asset_file_name(&entry.file_name().to_string_lossy(), &asset_id)
        })
        .map(|entry| entry.path())
        .collect::<Vec<_>>();
    if matches.len() > 1 {
        return Err("同一素材 ID 对应多个受管文件；为避免误删，已保留全部文件".into());
    }
    let deleted = if let Some(path) = matches.first() {
        fs::remove_file(path).map_err(|error| format!("无法删除受管素材：{error}"))?;
        true
    } else {
        false
    };
    Ok(WorkspaceAssetDeleteResult {
        project_id,
        asset_id,
        deleted,
    })
}

#[tauri::command]
fn save_project(path: String, content: String) -> Result<(), String> {
    fs::write(path, content).map_err(|e| e.to_string())
}

#[tauri::command]
fn save_media(
    app: tauri::AppHandle,
    path: String,
    source_path: Option<String>,
    data_url: Option<String>,
) -> Result<(), String> {
    if let Some(source) = source_path {
        // Keep the destination selected by the user unrestricted, but only
        // copy from an app-managed or file-picker-authorized source.  A
        // malicious/old imported project cannot use this command to exfiltrate
        // an arbitrary local file into an export chosen later.
        let source = authorized_media_source_path(&app, &source)?;
        fs::copy(source, path).map_err(|e| e.to_string())?;
        return Ok(());
    }
    if let Some(data) = data_url {
        let encoded = data
            .split_once(',')
            .map(|(_, body)| body)
            .ok_or("媒体数据格式不正确")?;
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(encoded)
            .map_err(|e| e.to_string())?;
        fs::write(path, bytes).map_err(|e| e.to_string())?;
        return Ok(());
    }
    Err("没有可保存的媒体内容".into())
}

