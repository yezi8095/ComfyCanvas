#[tauri::command]
async fn test_provider_connection(
    provider: String,
    endpoint: String,
    api_key: String,
    api_secret: Option<String>,
    model: String,
) -> Result<ProviderConnectionResult, String> {
    let endpoint = validated_http_endpoint(&provider, &endpoint)?.trim_end_matches('/');
    if provider != "Ollama（本地）" && api_key.trim().is_empty() {
        return Err("请先填写 API Key 或 Access Key".into());
    }
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(25))
        .build()
        .map_err(|error| format!("创建网络请求失败：{error}"))?;
    let display_model = (!model.trim().is_empty()).then(|| model.trim().to_string());
    match provider.as_str() {
        "Ollama（本地）" => {
            let base = endpoint.trim_end_matches('/').trim_end_matches("/v1");
            let response: serde_json::Value = client
                .get(format!("{base}/api/tags"))
                .send()
                .await
                .map_err(|error| format!("无法连接本地 Ollama：{error}"))?
                .error_for_status()
                .map_err(|error| format!("Ollama 连接失败：{error}"))?
                .json()
                .await
                .map_err(|error| format!("Ollama 返回的不是模型列表：{error}"))?;
            let count = response
                .get("models")
                .and_then(serde_json::Value::as_array)
                .map_or(0, Vec::len);
            if count == 0 {
                return Err(
                    "Ollama 已连接，但还没有已安装模型；请先执行 ollama pull <模型名>".into(),
                );
            }
            Ok(ProviderConnectionResult {
                provider,
                detail: format!("本地 Ollama 已连接，发现 {count} 个已安装模型；未创建生成任务。"),
                model: display_model,
            })
        }
        "Google Nano Banana" => {
            let base = if endpoint.ends_with("/v1") || endpoint.ends_with("/v1beta") {
                endpoint.to_string()
            } else {
                format!("{endpoint}/v1beta")
            };
            let name = display_model
                .as_deref()
                .unwrap_or("gemini-3.1-flash-image")
                .trim_start_matches("models/");
            checked_provider_response(
                "Google Nano Banana",
                client
                    .get(format!("{base}/models/{name}"))
                    .header("x-goog-api-key", api_key.trim())
                    .send()
                    .await
                    .map_err(|error| format!("无法连接 Google Gemini API：{error}"))?,
            )
            .await?;
            Ok(ProviderConnectionResult {
                provider,
                detail: format!("Gemini API Key 有效，已确认可读取模型 {name}；未创建生成任务。"),
                model: Some(name.to_string()),
            })
        }
        "可灵 Kling" => {
            let token = match api_secret
                .as_deref()
                .filter(|value| !value.trim().is_empty())
            {
                Some(secret) => kling_jwt(api_key.trim(), secret.trim())?,
                None => api_key.trim().to_string(),
            };
            let base = api_base(endpoint, "/v1");
            checked_provider_response(
                "可灵 Kling",
                client
                    .get(format!("{base}/videos/text2video?page_num=1&page_size=1"))
                    .bearer_auth(token)
                    .send()
                    .await
                    .map_err(|error| format!("无法连接可灵开放平台：{error}"))?,
            )
            .await?;
            Ok(ProviderConnectionResult {
                provider,
                detail: if api_secret
                    .as_deref()
                    .is_some_and(|value| !value.trim().is_empty())
                {
                    "Access Key 与 Secret Key 鉴权成功，已访问任务列表；未创建视频任务。".into()
                } else {
                    "单 API Key 鉴权成功，已访问任务列表；未创建视频任务。".into()
                },
                model: display_model,
            })
        }
        "豆包·火山方舟" => {
            let base = api_base(endpoint, "/api/v3");
            let name = display_model
                .as_deref()
                .ok_or("请填写火山方舟模型或推理接入点 ID")?;
            checked_provider_response(
                "豆包·火山方舟",
                client
                    .get(format!("{base}/models/{name}"))
                    .bearer_auth(api_key.trim())
                    .send()
                    .await
                    .map_err(|error| format!("无法连接火山方舟：{error}"))?,
            )
            .await?;
            Ok(ProviderConnectionResult {
                provider,
                detail: format!(
                    "火山方舟 API Key 有效，已确认可访问模型/接入点 {name}；未创建视频任务。"
                ),
                model: Some(name.to_string()),
            })
        }
        _ => {
            let url = if provider == "阿里百炼·万相" {
                let root = endpoint
                    .strip_suffix("/api/v1")
                    .or_else(|| endpoint.strip_suffix("/compatible-mode/v1"))
                    .unwrap_or(endpoint);
                format!("{root}/compatible-mode/v1/models")
            } else if endpoint.ends_with("/models") {
                endpoint.to_string()
            } else if endpoint.ends_with("/v1") {
                format!("{endpoint}/models")
            } else {
                format!("{endpoint}/v1/models")
            };
            let body = checked_provider_response(
                &provider,
                client
                    .get(url)
                    .bearer_auth(api_key.trim())
                    .send()
                    .await
                    .map_err(|error| format!("无法连接{provider}：{error}"))?,
            )
            .await?;
            let visible_models = body
                .get("data")
                .and_then(serde_json::Value::as_array)
                .or_else(|| body.get("models").and_then(serde_json::Value::as_array));
            let selected_visible = display_model.as_deref().map(|selected| {
                visible_models.is_some_and(|models| {
                    models.iter().any(|item| {
                        item.get("id")
                            .and_then(serde_json::Value::as_str)
                            .or_else(|| item.get("name").and_then(serde_json::Value::as_str))
                            .is_some_and(|id| id == selected)
                    })
                })
            });
            Ok(ProviderConnectionResult {
                detail: match selected_visible {
                    Some(true) => "API Key 有效，模型接口可访问，当前模型在平台列表中；未创建生成任务。".into(),
                    Some(false) => "API Key 有效，模型接口可访问；当前模型未出现在公开列表中，仍可作为私有、接入点或新模型 ID 手动保存。".into(),
                    None => "API Key 有效，模型接口可访问；未创建生成任务。".into(),
                },
                provider,
                model: display_model,
            })
        }
    }
}

fn normalize_kling_model_name(model: &str) -> String {
    let trimmed = model.trim();
    let normalized = trimmed.to_ascii_lowercase().replace(['.', '_'], "-");
    if matches!(
        normalized.as_str(),
        "kling-3-0-turbo"
            | "kling-v3-0-turbo"
            | "kling-3-turbo"
            | "kling-v3-turbo"
            | "kling-3-0"
            | "kling-v3-0"
    ) {
        "kling-v3".into()
    } else {
        trimmed.to_string()
    }
}

fn kling_supports_first_last(model: &str) -> bool {
    let model = model.trim().to_ascii_lowercase();
    model == "kling-v1-6" || model.contains("kling-v1-6")
}

fn validate_kling_video_contract(
    model: &str,
    mode: &str,
    quality: &str,
    duration: u32,
    audio: bool,
) -> Result<&'static str, String> {
    if !matches!(mode, "text" | "image" | "firstLast") {
        return Err(format!("可灵当前适配不支持视频模式：{mode}"));
    }
    if mode == "firstLast" && !kling_supports_first_last(model) {
        return Err(format!(
            "可灵模型“{}”未接入首尾帧合同；请改用 kling-v1-6 或切换到文生/图生",
            model.trim()
        ));
    }
    let quality = match validate_video_quality(quality)? {
        "720P" => "720P",
        "1080P" => "1080P",
        _ => {
            return Err(
                "可灵当前适配只会真实提交 720P（std）或 1080P（pro）；480P 不会被静默降级".into(),
            )
        }
    };
    if mode == "firstLast" && quality != "1080P" {
        return Err("可灵 v1.6 首尾帧仅支持 1080P；请将清晰度设为 1080P".into());
    }
    if !matches!(duration, 5 | 10) {
        return Err("可灵当前适配只提交 5 秒或 10 秒；不会将其它时长自动改写".into());
    }
    if audio {
        return Err("可灵当前视频适配未接入原生音频合同；请关闭音频后重试".into());
    }
    Ok(quality)
}

fn kling_image_payload(value: &str, label: &str) -> Result<String, String> {
    let value = validate_image_reference(value, label)?;
    if let Some((_, encoded)) = value.split_once(',') {
        return Ok(encoded.to_string());
    }
    Ok(value)
}

async fn generate_kling_video(
    endpoint: &str,
    access_key: &str,
    secret_key: Option<&str>,
    prompt: &str,
    model: &str,
    mode: &str,
    ratio: &str,
    quality: &str,
    duration: u32,
    first_frame_url: Option<&str>,
    last_frame_url: Option<&str>,
    audio: bool,
) -> Result<VideoGenerationResult, String> {
    let model = normalize_kling_model_name(model);
    validate_provider_request("可灵 Kling", endpoint, access_key, prompt, &model)?;
    let _ratio = validate_video_ratio(ratio)?;
    let quality = validate_kling_video_contract(&model, mode, quality, duration, audio)?;
    let token = match secret_key.filter(|value| !value.trim().is_empty()) {
        Some(secret) => kling_jwt(access_key.trim(), secret.trim())?,
        None => access_key.trim().to_string(),
    };
    let is_first_last = mode == "firstLast";
    if mode != "text" && first_frame_url.is_none() {
        return Err("可灵图生视频需要一张首帧图片".into());
    }
    if is_first_last && last_frame_url.is_none() {
        return Err("可灵首尾帧视频需要首帧和尾帧各一张图片".into());
    }
    let route = if mode == "text" {
        "text2video"
    } else {
        "image2video"
    };
    let base = api_base(endpoint, "/v1");
    let mut payload = serde_json::json!({
      "model_name": model, "prompt": prompt, "negative_prompt": "", "cfg_scale": 0.5,
      "mode": if is_first_last || quality == "1080P" { "pro" } else { "std" },
      "aspect_ratio": ratio, "duration": duration.to_string()
    });
    if let Some(first_frame_url) = first_frame_url {
        payload["image"] =
            serde_json::Value::String(kling_image_payload(first_frame_url, "可灵首帧图片")?);
    }
    if let Some(last_frame_url) = last_frame_url {
        if is_first_last {
            payload["image_tail"] =
                serde_json::Value::String(kling_image_payload(last_frame_url, "可灵尾帧图片")?);
        } else {
            return Err("可灵图生视频不接受尾帧图片；请切换到首尾帧模式".into());
        }
    }
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(45))
        .build()
        .map_err(|error| format!("创建可灵网络请求失败：{error}"))?;
    let response = client
        .post(format!("{base}/videos/{route}"))
        .bearer_auth(&token)
        .json(&payload)
        .send()
        .await
        .map_err(|error| provider_network_error("可灵 Kling", "创建视频任务", &error))?;
    let created = provider_json_response("可灵 Kling", "创建视频任务", response).await?;
    let task_id = created
        .pointer("/data/task_id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("可灵没有返回任务编号：{created}"))?
        .to_string();
    let request_id = created
        .get("request_id")
        .and_then(serde_json::Value::as_str)
        .map(str::to_string);
    for _ in 0..240 {
        tokio::time::sleep(Duration::from_secs(3)).await;
        let response = client
            .get(format!("{base}/videos/{route}/{task_id}"))
            .bearer_auth(&token)
            .send()
            .await
            .map_err(|error| provider_network_error("可灵 Kling", "查询视频任务", &error))?;
        let task = provider_json_response("可灵 Kling", "查询视频任务", response).await?;
        let task_status = task
            .pointer("/data/task_status")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("");
        if matches!(task_status, "succeed" | "succeeded" | "SUCCESS") {
            let video_url = task
                .pointer("/data/task_result/videos/0/url")
                .and_then(serde_json::Value::as_str)
                .or_else(|| {
                    task.pointer("/data/task_result/videos/0/video_url")
                        .and_then(serde_json::Value::as_str)
                })
                .ok_or_else(|| format!("可灵任务已完成但没有返回视频地址：{task}"))?
                .to_string();
            return Ok(VideoGenerationResult {
                task_id,
                request_id,
                video_url,
            });
        }
        if matches!(task_status, "failed" | "canceled" | "cancelled" | "FAILURE") {
            let message = task
                .pointer("/data/task_status_msg")
                .and_then(serde_json::Value::as_str)
                .unwrap_or("平台未提供失败原因");
            return Err(format!("可灵任务失败：{message}"));
        }
    }
    Err("可灵任务等待超时（12 分钟），请在可灵开放平台查看任务状态".into())
}

fn doubao_reference_limit(model: &str) -> usize {
    let model = model.trim().to_ascii_lowercase();
    if model.contains("seedance-2-0") {
        9
    } else if model.contains("seedance-1-0-lite-i2v") {
        4
    } else {
        0
    }
}

fn doubao_supports_mode(model: &str, mode: &str) -> bool {
    let model = model.trim().to_ascii_lowercase();
    let supports_seedance_pro = (model.contains("seedance-1-0-pro")
        || model.contains("seedance-1-5-pro"))
        && !model.contains("pro-fast");
    if model.contains("seedance-2-0") {
        matches!(mode, "text" | "image" | "firstLast" | "reference")
    } else if model.contains("seedance-1-0-lite-i2v") {
        matches!(mode, "image" | "firstLast" | "reference")
    } else if supports_seedance_pro {
        matches!(mode, "text" | "image" | "firstLast")
    } else {
        mode == "text"
    }
}

async fn generate_doubao_video(
    endpoint: &str,
    api_key: &str,
    prompt: &str,
    model: &str,
    ratio: &str,
    quality: &str,
    duration: u32,
    mode: &str,
    image_urls: &[String],
    first_frame_url: Option<&str>,
    last_frame_url: Option<&str>,
    audio: bool,
) -> Result<VideoGenerationResult, String> {
    validate_provider_request("豆包·火山方舟", endpoint, api_key, prompt, model)?;
    let ratio = validate_video_ratio(ratio)?;
    let quality = validate_video_quality(quality)?;
    if !(2..=12).contains(&duration) {
        return Err("豆包视频时长必须在 2 到 12 秒之间；当前请求不会自动改写时长".into());
    }
    if audio {
        return Err("豆包当前视频适配未接入原生音频合同；请关闭音频后重试".into());
    }
    if !doubao_supports_mode(model, mode) {
        return Err(format!(
            "豆包模型“{}”未接入{}；请切换模型或模式",
            model.trim(),
            match mode {
                "text" => "文生视频",
                "image" => "图生视频",
                "firstLast" => "首尾帧视频",
                "reference" => "多参考视频",
                _ => "当前视频模式",
            }
        ));
    }
    let base = api_base(
        validated_http_endpoint("豆包·火山方舟", endpoint)?,
        "/api/v3",
    );
    let prompt = format!(
        "{} --ratio {} --dur {} --resolution {}",
        prompt.trim(),
        ratio,
        duration,
        quality.to_ascii_lowercase()
    );
    let mut content = vec![serde_json::json!({"type":"text","text":prompt})];
    let normalized_image_urls = image_urls
        .iter()
        .map(String::as_str)
        .map(|url| validate_image_reference(url, "豆包参考图"))
        .collect::<Result<Vec<_>, _>>()?;
    let image_urls: Vec<&str> = normalized_image_urls.iter().map(String::as_str).collect();
    let first_frame_url = first_frame_url
        .map(|url| validate_image_reference(url, "豆包首帧图片"))
        .transpose()?;
    let last_frame_url = last_frame_url
        .map(|url| validate_image_reference(url, "豆包尾帧图片"))
        .transpose()?;
    let model_id = model.trim().to_ascii_lowercase();
    match mode {
        "text" => {
            if !image_urls.is_empty() || first_frame_url.is_some() || last_frame_url.is_some() {
                return Err("豆包文生视频不接受图片、首帧或尾帧输入".into());
            }
        }
        "image" => {
            if last_frame_url.is_some() {
                return Err("豆包图生视频不接受尾帧图片；请使用首尾帧模式".into());
            }
            let first_frame_url = first_frame_url.ok_or("豆包图生视频需要一张首帧图片")?;
            if image_urls.iter().any(|url| *url != first_frame_url) {
                return Err("豆包图生视频只接受与首帧相同的 1 张图片；请移除额外参考图".into());
            }
            content.push(serde_json::json!({
                "type":"image_url",
                "image_url":{"url":first_frame_url},
                "role":"first_frame"
            }));
        }
        "firstLast" => {
            let first_frame_url = first_frame_url.ok_or("豆包首尾帧视频缺少首帧图片")?;
            let last_frame_url = last_frame_url.ok_or("豆包首尾帧视频缺少尾帧图片")?;
            if first_frame_url == last_frame_url {
                return Err("豆包首尾帧视频需要两张不同的图片".into());
            }
            if image_urls.len() > 2
                || image_urls
                    .iter()
                    .any(|url| *url != first_frame_url && *url != last_frame_url)
            {
                return Err(
                    "豆包首尾帧视频只接受与首帧、尾帧对应的两张图片；请移除额外参考图".into(),
                );
            }
            content.push(serde_json::json!({
                "type":"image_url",
                "image_url":{"url":first_frame_url},
                "role":"first_frame"
            }));
            content.push(serde_json::json!({
                "type":"image_url",
                "image_url":{"url":last_frame_url},
                "role":"last_frame"
            }));
        }
        "reference" => {
            if first_frame_url.is_some() || last_frame_url.is_some() {
                return Err("豆包多参考视频不接受独立首帧或尾帧；请将图片放在参考图列表".into());
            }
            let reference_limit = doubao_reference_limit(&model_id);
            if image_urls.is_empty() || image_urls.len() > reference_limit {
                return Err(format!(
                    "豆包多参考视频需要 1-{reference_limit} 张图片（当前 {} 张）",
                    image_urls.len()
                ));
            }
            content.extend(image_urls.iter().map(|url| {
                serde_json::json!({
                    "type":"image_url",
                    "image_url":{"url":url},
                    "role":"reference_image"
                })
            }));
        }
        unsupported => return Err(format!("豆包当前适配不支持视频模式：{unsupported}")),
    }
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(45))
        .build()
        .map_err(|error| format!("创建豆包网络请求失败：{error}"))?;
    let response = client
        .post(format!("{base}/contents/generations/tasks"))
        .bearer_auth(api_key.trim())
        .json(&serde_json::json!({"model":model,"content":content}))
        .send()
        .await
        .map_err(|error| provider_network_error("豆包·火山方舟", "创建视频任务", &error))?;
    let created = provider_json_response("豆包·火山方舟", "创建视频任务", response).await?;
    let task_id = created
        .get("id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("豆包没有返回任务编号：{created}"))?
        .to_string();
    for _ in 0..240 {
        tokio::time::sleep(Duration::from_secs(3)).await;
        let response = client
            .get(format!("{base}/contents/generations/tasks/{task_id}"))
            .bearer_auth(api_key.trim())
            .send()
            .await
            .map_err(|error| provider_network_error("豆包·火山方舟", "查询视频任务", &error))?;
        let task = provider_json_response("豆包·火山方舟", "查询视频任务", response).await?;
        let task_status = task
            .get("status")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("");
        if task_status == "succeeded" {
            let video_url = task
                .pointer("/content/video_url")
                .and_then(serde_json::Value::as_str)
                .ok_or_else(|| format!("豆包任务已完成但没有返回视频地址：{task}"))?
                .to_string();
            return Ok(VideoGenerationResult {
                task_id,
                request_id: None,
                video_url,
            });
        }
        if matches!(task_status, "failed" | "cancelled" | "canceled") {
            let message = task
                .pointer("/error/message")
                .and_then(serde_json::Value::as_str)
                .unwrap_or("平台未提供失败原因");
            return Err(format!("豆包任务{task_status}：{message}"));
        }
    }
    Err("豆包任务等待超时（12 分钟），请在火山方舟控制台查看任务状态".into())
}

