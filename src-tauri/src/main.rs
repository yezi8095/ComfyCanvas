async fn generate_alibaba_wan_video_request(
    endpoint: &str,
    api_key: &str,
    prompt: &str,
    model: &str,
    mode: &str,
    ratio: &str,
    quality: &str,
    duration: u32,
    audio: bool,
    first_frame_url: Option<&str>,
    last_frame_url: Option<&str>,
) -> Result<VideoGenerationResult, String> {
    validate_provider_request("阿里百炼·万相", endpoint, api_key, prompt, model)?;
    let (quality, ratio) =
        validate_wan_video_contract(model, mode, ratio, quality, duration, audio)?;
    let endpoint = validated_http_endpoint("阿里百炼·万相", endpoint)?.trim_end_matches('/');
    let base = if endpoint.ends_with("/api/v1") {
        endpoint.to_string()
    } else {
        format!("{endpoint}/api/v1")
    };
    let size = match (ratio, quality) {
        ("9:16", "480P") => "480*832",
        ("9:16", "1080P") => "1080*1920",
        ("9:16", _) => "720*1280",
        ("1:1", _) => "960*960",
        ("4:3", _) => "960*720",
        ("3:4", _) => "720*960",
        ("21:9", _) => "1472*624",
        (_, "480P") => "832*480",
        (_, "1080P") => "1920*1080",
        _ => "1280*720",
    };
    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(45))
        .build()
        .map_err(|error| format!("创建网络请求失败：{error}"))?;
    let (create_url, payload) = match mode {
        "text" => (
            format!("{base}/services/aigc/video-generation/video-synthesis"),
            serde_json::json!({
              "model": model,
              "input": { "prompt": prompt },
              "parameters": {
                "size": size,
                "duration": duration,
                "audio": audio,
                "prompt_extend": true
              }
            }),
        ),
        "image" => {
            let img_url = first_frame_url.ok_or("万相图生视频需要一张首帧图片")?;
            (
                format!("{base}/services/aigc/video-generation/video-synthesis"),
                serde_json::json!({
                  "model": model,
                  "input": { "prompt": prompt, "img_url": img_url },
                  "parameters": {
                    "resolution": quality,
                    "duration": duration,
                    "audio": audio,
                    "prompt_extend": true
                  }
                }),
            )
        }
        "firstLast" => {
            let first_frame_url = first_frame_url.ok_or("万相首尾帧视频缺少首帧图片")?;
            let last_frame_url = last_frame_url.ok_or("万相首尾帧视频缺少尾帧图片")?;
            (
                format!("{base}/services/aigc/image2video/video-synthesis"),
                serde_json::json!({
                  "model": model,
                  "input": {
                    "prompt": prompt,
                    "first_frame_url": first_frame_url,
                    "last_frame_url": last_frame_url
                  },
                  "parameters": {
                    "resolution": quality,
                    "prompt_extend": true
                  }
                }),
            )
        }
        unsupported => return Err(format!("万相当前适配不支持视频模式：{unsupported}")),
    };
    let response = client
        .post(create_url)
        .bearer_auth(api_key)
        .header("X-DashScope-Async", "enable")
        .json(&payload)
        .send()
        .await
        .map_err(|error| provider_network_error("阿里百炼·万相", "创建视频任务", &error))?;
    let created = provider_json_response("阿里百炼·万相", "创建视频任务", response).await?;
    let task_id = created
        .pointer("/output/task_id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("阿里百炼没有返回任务编号：{created}"))?
        .to_string();
    let request_id = created
        .pointer("/request_id")
        .and_then(serde_json::Value::as_str)
        .map(str::to_string);
    let poll_url = format!("{base}/tasks/{task_id}");
    for _ in 0..240 {
        tokio::time::sleep(Duration::from_secs(3)).await;
        let response = client
            .get(&poll_url)
            .bearer_auth(api_key)
            .send()
            .await
            .map_err(|error| provider_network_error("阿里百炼·万相", "查询视频任务", &error))?;
        let task = provider_json_response("阿里百炼·万相", "查询视频任务", response).await?;
        let task_status = task
            .pointer("/output/task_status")
            .and_then(serde_json::Value::as_str)
            .unwrap_or("");
        if task_status == "SUCCEEDED" {
            let video_url = task
                .pointer("/output/video_url")
                .and_then(serde_json::Value::as_str)
                .or_else(|| {
                    task.pointer("/output/video_urls/0")
                        .and_then(serde_json::Value::as_str)
                })
                .ok_or_else(|| format!("任务已完成但没有返回视频地址：{task}"))?
                .to_string();
            return Ok(VideoGenerationResult {
                task_id,
                request_id,
                video_url,
            });
        }
        if matches!(task_status, "FAILED" | "CANCELED" | "CANCELLED") {
            let message = task
                .pointer("/output/message")
                .and_then(serde_json::Value::as_str)
                .or_else(|| task.pointer("/message").and_then(serde_json::Value::as_str))
                .unwrap_or("平台未提供失败原因");
            return Err(format!("阿里百炼任务{task_status}：{message}"));
        }
    }
    Err("阿里百炼任务等待超时（12 分钟），请在百炼控制台查看任务状态".into())
}

fn api_base(endpoint: &str, suffix: &str) -> String {
    let endpoint = endpoint.trim().trim_end_matches('/');
    if endpoint.ends_with(suffix) {
        endpoint.to_string()
    } else {
        format!("{endpoint}{suffix}")
    }
}

fn kling_jwt(access_key: &str, secret_key: &str) -> Result<String, String> {
    type HmacSha256 = Hmac<Sha256>;
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|error| format!("系统时间不可用：{error}"))?
        .as_secs();
    let header = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(
        serde_json::to_vec(&serde_json::json!({"alg":"HS256","typ":"JWT"}))
            .map_err(|error| error.to_string())?,
    );
    let payload = base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(
        serde_json::to_vec(
            &serde_json::json!({"iss":access_key,"exp":now + 1800,"nbf":now.saturating_sub(5)}),
        )
        .map_err(|error| error.to_string())?,
    );
    let signing_input = format!("{header}.{payload}");
    let mut mac = HmacSha256::new_from_slice(secret_key.as_bytes())
        .map_err(|error| format!("可灵 Secret Key 无效：{error}"))?;
    mac.update(signing_input.as_bytes());
    let signature =
        base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(mac.finalize().into_bytes());
    Ok(format!("{signing_input}.{signature}"))
}

